// zzOverlayState 全场粒子状态的逐字摘要（%v 全精度，20 个字段；与zzParticlesState 同口径）。
func zzOverlayState(f *Field) string {
	out := ""
	for i := range f.parts {
		p := &f.parts[i]
		out += fmt.Sprint(p.x, "|", p.y, "|", p.vx, "|", p.vy, "|", p.vxBase, "|", p.sc, "|",
			p.rot, "|", p.rotV, "|", p.alpha, "|", p.amp, "|", p.omega, "|", p.phase, "|",
			p.kind, "|", p.depth, "|", p.spr, "|", p.idx, "|", p.brightnessMul, "|",
			p.alphaMul, "|", p.scaleMul, "|", p.mirror, "\n")
	}
	return out
}

func zzOverlayDigest(s string) uint64 {
	h := fnv.New64a()
	h.Write([]byte(s))
	return h.Sum64()
}

