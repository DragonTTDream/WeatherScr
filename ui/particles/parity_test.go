// spriteNetDivWant = ui 侧注入给 SizeFlakeByTarget 的净倍率分母
// （真值在 ui/assets.go:375 = spriteNetDiv 2.0，本包不持有一份真值 ⇒ 测试里按注入值写出）。
const spriteNetDivWant = 2.0

// TestParticlesParity 钉死迁移：导出函数与常量在固定输入下逐位等于旧实现。
func TestParticlesParity(t *testing.T) {
	got := map[string]string{}
	P := func(k string, v ...interface{}) { got[k] = fmt.Sprint(v...) }

	P("const/rainExposure", particles.RainExposure)
	P("const/rainSlantBase", particles.RainSlantBase)
	P("const/windJitterAmp", particles.WindJitterAmp)
	P("const/flakePxLo", particles.FlakePxLo)
	P("const/flakePxHi", particles.FlakePxHi)
	P("const/flakeAlphaMin", particles.FlakeAlphaMin)
	P("const/recycleYHi", particles.RecycleYHi)
	P("const/recycleYLo", particles.RecycleYLo)
	P("const/rainStreakCapPx", fmt.Sprint(particles.RainStreakCapPx))

	for _, spr := range []int{-1, 0, 1, 2, 3, 4, 5, 6, 7, 8, 99} {
		P(fmt.Sprintf("streakCap/%d", spr), particles.RainStreakCapFor(spr))
	}
	for _, d := range []float64{0, 0.1, 0.35, 0.4, 0.5, 0.7, 0.71, 1} {
		a, l := particles.RainDepthFactor(d)
		P(fmt.Sprintf("depthFactor/%v", d), a, "/", l)
		P(fmt.Sprintf("baseAlpha/%v", d), particles.RainBaseAlpha(d))
	}
	for _, c := range [][2]float64{{0, 0}, {0.15, 0}, {0.5, 7}, {0.999, 7}, {1, 7}, {1, 1}, {0.3, 3}} {
		P(fmt.Sprintf("dropTier/%v/%d", c[0], int(c[1])), particles.DropSpriteTier(c[0], int(c[1])))
	}
	for _, ix := range []int{0, 1, 3, 5, 7, 8, 11} {
		P(fmt.Sprintf("flakeIdx/%d/3", ix), particles.FlakeSpriteIndex(ix, 3))
	}
	for _, seed := range []int64{20261026, 7} {
		r := rand.New(rand.NewSource(seed))
		P(fmt.Sprintf("moteIdx/%d", seed),
			particles.MoteSpriteIndex(r, 4), particles.MoteSpriteIndex(r, 4),
			particles.MoteSpriteIndex(r, 4), particles.MoteSpriteIndex(r, 1))
	}

	for _, seed := range []int64{20261026, 7, 1} {
		for _, fresh := range []bool{true, false} {
			r := rand.New(rand.NewSource(seed))
			for _, depth := range []float64{0, 0.25, 0.5, 0.74, 1} {
				q := particles.SpawnDrop(r, fresh, depth)
				P(fmt.Sprintf("drop/%d/%v/%v", seed, fresh, depth), q.X, q.Y, q.Sc, q.Alpha, q.Vy, q.Vx)
			}
			r = rand.New(rand.NewSource(seed))
			for _, depth := range []float64{0, 0.25, 0.5, 0.74, 1} {
				q := particles.SpawnFlake(r, fresh, depth, 0)
				P(fmt.Sprintf("flake/%d/%v/%v", seed, fresh, depth),
					q.X, q.Y, q.Sc, q.Alpha, q.Vy, q.Vx, q.Omega, q.Amp, q.RotV, q.Phase)
			}
			r = rand.New(rand.NewSource(seed))
			for mi := range []float64{0, 0.25, 0.5, 0.74, 1} {
				q := particles.SpawnMote(r, fresh)
				P(fmt.Sprintf("mote/%d/%v#%d", seed, fresh, mi), q.X, q.Y, q.Sc, q.Alpha, q.Vx, q.Vy, q.RotV)
			}
		}
	}

	for _, seed := range []int64{20261026, 7} {
		r := rand.New(rand.NewSource(seed))
		for _, in := range [][3]float64{{18, 0, 0.75}, {26, 0.5, 1.0}, {36, 1, 1.25}, {48, 0.3, 0.9}} {
			sc, ok := particles.SizeFlakeByTarget(r, spriteNetDivWant, in[0], in[1], in[2])
			P(fmt.Sprintf("sizeFlake/%d/%v/%v/%v", seed, in[0], in[1], in[2]), sc, ok)
		}
		sc, ok := particles.SizeFlakeByTarget(r, spriteNetDivWant, 0, 0.5, 1)
		P("sizeFlake/guard/0", sc, ok)
		sc, ok = particles.SizeFlakeByTarget(r, spriteNetDivWant, 18, 0.5, 0)
		P("sizeFlake/guard/scaleMul0", sc, ok)
	}

	for _, pt := range [][2]float64{{0.5, 0.5}, {0.5, 1.15}, {0.5, 1.151}, {0.5, -0.35}, {0.5, -0.351}, {1.25, 0.5}, {1.251, 0.5}, {-0.35, 0.5}, {-0.351, 0.5}} {
		P(fmt.Sprintf("offscreen/%v/%v", pt[0], pt[1]), particles.OffscreenCenter(pt[0], pt[1]))
	}

	bad := 0
	// 本包只经导出面覆盖这些前缀（field/* 与 ui 侧 frames/* 的逐字键归 ui 对拍件）。
	prefixes := []string{"const/", "streakCap/", "depthFactor/", "baseAlpha/", "dropTier/",
		"flakeIdx/", "moteIdx/", "drop/", "flake/", "mote/", "sizeFlake/", "offscreen/"}
	cov := func(k string) bool {
		for _, p := range prefixes {
			if strings.HasPrefix(k, p) {
				return true
			}
		}
		return false
	}
	bad = 0
	for k, want := range particlesWant {
		if !cov(k) {
			continue
		}
		if got[k] != want {
			bad++
			if bad <= 20 {
				t.Errorf("对拍红 %s\n\t旧 = %s\n\t新 = %s", k, want, got[k])
			}
		}
	}
	for k := range got {
		if _, ok := particlesWant[k]; !ok {
			t.Errorf("本包算出但 want 里没有的键 = %s = %s", k, got[k])
			bad++
		}
	}
	if bad != 0 {
		t.Fatalf("粒子对拍红 %d/%d 键", bad, len(particlesWant))
	}
	t.Logf("PARITY ok: 导出面 %d 键逐位等于迁移前旧实现", len(got))
}

// framesCases = 200 帧连跑的 16 组（4 类 × 两制 × 2 种子）。
func framesCases() []struct {
	cls   effect.Class
	name  string
	isDay bool
	w, h  int
	seed  int64
} {
	type cs struct {
		cls   effect.Class
		name  string
		isDay bool
	}
	var out []struct {
		cls   effect.Class
		name  string
		isDay bool
		w, h  int
		seed  int64
	}
	for _, c := range []cs{
		{effect.Rain, "rain", true},
		{effect.Thunder, "thunder", false},
		{effect.Snow, "snow", true},
		{effect.Dust, "dust", true},
	} {
		for _, dims := range [][2]int{{ui.PortraitW, ui.PortraitH}, {ui.PortraitH, ui.PortraitW}} {
			for _, seed := range []int64{20261026, 7} {
				out = append(out, struct {
					cls   effect.Class
					name  string
					isDay bool
					w, h  int
					seed  int64
				}{c.cls, c.name, c.isDay, dims[0], dims[1], seed})
			}
		}
	}
	return out
}

func zzFramesDigest(f *ui.Field) uint64 {
	h := fnv.New64a()
	h.Write([]byte(f.DebugStats(f.TotalCount())))
	return h.Sum64()
}

// TestParticlesParityFrames 钉死"同种子连跑 200 帧 ⇒ 逐帧位移序列"（判据 3）。
//
// 取数（WS_PRE_PARTICLES2=1 ⇒ 只打印不比）：
//
//	WS_PRE_PARTICLES2=1 go test -tags=novulkan,nox11 -count=1 -run TestParticlesParityFrames ./ui/particles -v
func TestParticlesParityFrames(t *testing.T) {
	printOnly := os.Getenv("WS_PRE_PARTICLES2") == "1"
	markAt := map[int]int{0: 0, 1: 1, 2: 2, 100: 3, 199: 4}
	for _, c := range framesCases() {
		f := ui.NewField(c.cls, c.isDay, c.seed)
		h := fnv.New64a()
		var marks [5]uint64
		for k := 0; k < 200; k++ {
			f.Step(time.Second/60, c.w, c.h)
			d := zzFramesDigest(f)
			h.Write([]byte(fmt.Sprint(d)))
			if i, ok := markAt[k]; ok {
				marks[i] = d
			}
		}
		tag := fmt.Sprintf("frames200/%s/%dx%d/%d", c.name, c.w, c.h, c.seed)
		got := map[string]string{
			tag + "/acc":     fmt.Sprint(h.Sum64()),
			tag + "/mark0":   fmt.Sprint(marks[0]),
			tag + "/mark1":   fmt.Sprint(marks[1]),
			tag + "/mark2":   fmt.Sprint(marks[2]),
			tag + "/mark100": fmt.Sprint(marks[3]),
			tag + "/mark199": fmt.Sprint(marks[4]),
		}
		for k, v := range got {
			if printOnly {
				fmt.Printf("PRE %s = %s\n", k, v)
				continue
			}
			want, ok := particlesWant[k]
			if !ok {
				t.Fatalf("200 帧对拍缺 want 键 = %s（取数件没覆盖）", k)
			}
			if v != want {
				t.Fatalf("200 帧连跑对拍红 %s\n\t旧 = %s\n\t新 = %s", k, want, v)
			}
		}
	}
	if printOnly {
		t.Skip("WS_PRE_PARTICLES2=1 ⇒ 只打印取数")
	}
	t.Logf("PARITY ok: 16 组 × 200 帧逐帧序列逐位等于迁移前旧实现")
}
