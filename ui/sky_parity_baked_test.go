// skyFnv / skySmp = 与 ui/sky/parity_test.go 同一份取样口径（FNV-64a 全图校验和 + 定点取样）。
func skyFnv(img *image.NRGBA) uint64 {
	h := uint64(14695981039346656037)
	for _, b := range img.Pix {
		h ^= uint64(b)
		h *= 1099511628211
	}
	return h
}

func skySmp(img *image.NRGBA, x, y int) [4]uint8 {
	b := img.Bounds()
	if x < b.Min.X {
		x = b.Min.X
	}
	if y < b.Min.Y {
		y = b.Min.Y
	}
	if x > b.Max.X-1 {
		x = b.Max.X - 1
	}
	if y > b.Max.Y-1 {
		y = b.Max.Y - 1
	}
	i := img.PixOffset(x, y)
	return [4]uint8{img.Pix[i], img.Pix[i+1], img.Pix[i+2], img.Pix[i+3]}
}

