func TestOverlayParity(t *testing.T) {
	got := map[string]string{}
	P := func(k string, v ...interface{}) { got[k] = fmt.Sprint(v...) }

	// ---- ① 专属常量 ----
	P("const/fogScBase", overlay.FogScBase)
	P("const/fogScSpan", overlay.FogScSpan)
	P("const/fogAlphaMul", overlay.FogAlphaMul)
	P("const/snowFogCurtainN", overlay.SnowFogCurtainN)
	P("const/flashRadiusFrac", overlay.FlashRadiusFrac)
	P("const/flashAmpMax", overlay.FlashAmpMax)
	P("const/flashBoostMax", overlay.FlashBoostMax)
	P("const/flashAnchorY", overlay.FlashAnchorY)
	P("const/boltFlashMin", overlay.BoltFlashMin)
	P("const/boltAlphaMax", overlay.BoltAlphaMax)
	P("const/boltLenFrac", overlay.BoltLenFrac)
	P("const/boltGlowSigmaFrac", overlay.BoltGlowSigmaFrac)
	P("const/boltGlowMaskN", overlay.BoltGlowMaskN)

	// ---- ① 雾团屏上倍率（netScale = 旧实现里的那个常量值 1.0，见 ui/assets.go:377） ----
	netScale := 1.0
	for _, in := range [][3]float64{{1.3, 0, 0.75}, {2.05, 0.5, 1.0}, {2.8, 1, 1.25}, {1.3, 0.2, 1.0}, {2.8, 0.8, 0.9}} {
		P(fmt.Sprintf("fogScale/%v/%v/%v", in[0], in[1], in[2]), overlay.FogScale(in[0], in[1], in[2], netScale))
	}

	// ---- ① 雾团变体轮换 ----
	for _, c := range [][3]int{{0, 4, 9}, {1, 4, 9}, {5, 4, 9}, {9, 4, 9}, {7, 0, 9}, {8, 0, 9}, {11, 0, 3}, {3, 4, 0}} {
		P(fmt.Sprintf("fogIdx/%d/%d/%d", c[0], c[1], c[2]), overlay.FogSpriteIndex(c[0], c[1], c[2]))
	}

	// ---- ① 雾团屏宽封顶（贴图表/退路 = 合成表，与取数件同一份输入） ----
	syn := []image.Point{{1024, 512}, {800, 400}, {640, 640}}
	fb := image.Point{X: 999, Y: 333}
	for _, c := range []struct {
		sc, depth, scaleMul, cap float64
		spr                      int
		fb                       image.Point
		nFog                     int
	}{
		{2.8, 1, 1.25, 540, 0, fb, 3},
		{2.8, 1, 1.25, 346, 0, fb, 3},
		{1.3, 0.2, 1.0, 540, 1, fb, 3},
		{2.05, 0.5, 1.0, 0, 2, fb, 3},
		{0, 0.5, 1, 540, 0, fb, 3},
		{2.8, 0.8, 0.9, 1e9, 2, fb, 3},
		{2.8, 0.8, 0.9, 540, 9, fb, 3},
		{2.8, 0.8, 0.9, 540, 9, image.Point{}, 3},
		{2.8, 0.8, 0.9, 540, 9, image.Point{}, 0},
	} {
		sc := overlay.ClampFogWidthPx(c.sc, c.depth, c.scaleMul, netScale, c.cap, c.spr, syn[:c.nFog], c.fb)
		P(fmt.Sprintf("clampFog/%v/%v/%v/%v/%d/%d/%d", c.sc, c.depth, c.scaleMul, c.cap, c.spr, c.fb.X, c.nFog), sc)
	}

	// ---- ① 局域提亮掩膜（锚点 = 入参，旧实现里读 Field 的闪现落点） ----
	for _, an := range [][2]float64{{0.5, 0.12}, {0.15, 0.06}, {0.85, 0.20}, {0, 0}} {
		for _, pt := range [][2]float64{{0.5, 0.12}, {0.5, 0.121}, {0.2, 0.1}, {0.85, 0.9}, {1.2, 0.5}, {0.15, 0.06}} {
			P(fmt.Sprintf("flashMask/%v/%v/%v/%v", an[0], an[1], pt[0], pt[1]),
				overlay.FlashMaskAt(an[0], an[1], pt[0], pt[1]))
		}
	}

	// ---- ① 闪电绘制矩形 ----
	for _, c := range [][4]int{{512, 1024, 1080, 1920}, {300, 900, 1920, 1080}, {1, 1, 1080, 1920}, {640, 1280, 640, 1100}} {
		dw, dh := overlay.BoltRectPx(image.Point{X: c[0], Y: c[1]}, c[2], c[3])
		P(fmt.Sprintf("boltRect/%d/%d/%d/%d", c[0], c[1], c[2], c[3]), dw, "/", dh)
	}

	// ---- ① 高斯核 ----
	for _, s := range []float64{0.03, 0.5, 1, 2.4, 0.49} {
		k := overlay.GaussKernel(s)
		sum := 0.0
		for _, v := range k {
			sum += v
		}
		P(fmt.Sprintf("gauss/%v", s), len(k), k[len(k)/2], "sum", sum)
	}

	// ---- ① 雾团生成 / 雪天灰幕生成（固定种子 + 固定落位口 = 随机数取用序列逐字对拍） ----
	for _, seed := range []int64{20261026, 7, 1} {
		for _, depth := range []float64{0, 0.25, 0.5, 0.74, 1} {
			r := rand.New(rand.NewSource(seed))
			q := overlay.SpawnFog(r, depth, func() float64 { return 0.4242 })
			P(fmt.Sprintf("spawnFog/%d/%v", seed, depth), q.X, q.Y, q.Sc, q.Alpha, q.Vx, q.Vy, q.Depth)
			for _, idx := range []int{85, 171, 257, 0, 86} {
				r2 := rand.New(rand.NewSource(seed))
				q2 := overlay.SpawnSnowCurtain(r2, depth, idx, func() float64 { return 0.7071 })
				P(fmt.Sprintf("spawnSnow/%d/%v/%d", seed, depth, idx),
					q2.X, q2.Y, q2.Sc, q2.Alpha, q2.Vx, q2.Vy, q2.Depth)
			}
		}
	}

	// ---- 比对 ----
	bad := 0
	for k, want := range overlayWant {
		if got[k] != want {
			bad++
			if bad <= 20 {
				t.Errorf("对拍红 %s\n\t旧 = %s\n\t新 = %s", k, want, got[k])
			}
		}
	}
	for k := range got {
		if _, ok := overlayWant[k]; !ok {
			t.Errorf("新侧多出的键（取数件没覆盖）= %s = %s", k, got[k])
			bad++
		}
	}
	if bad == 0 {
		t.Logf("PARITY ok: %d 键逐位相等", len(overlayWant))
	} else {
		t.Fatalf("叠加层对拍红 %d/%d 键", bad, len(overlayWant))
	}
}
